import type { SceneIntroKey, SceneKind } from '../site-motion.type'
import type { Scene } from './scene.kit'

// The scene intros, one file per kind of event, each loaded only when a site uses one of its scenes.
type SceneModule = { scenes: Record<string, Scene> }
const loaders: Record<SceneKind, () => Promise<SceneModule>> = {
  any: () => import('./any'),
  wedding: () => import('./wedding'),
  party: () => import('./party'),
  business: () => import('./business'),
  memorial: () => import('./memorial'),
}

/** The scene for a key, loaded on demand. */
export async function loadScene(kind: SceneKind, key: SceneIntroKey): Promise<Scene | undefined> {
  const { scenes } = await loaders[kind]()
  return scenes[key]
}

